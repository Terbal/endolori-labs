function applyLang(lang){
  document.documentElement.lang = lang;
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-lang-switch]').forEach(sw=>{
    sw.querySelectorAll('button').forEach(b=> b.classList.toggle('active', b.dataset.lang===lang));
  });
  document.querySelectorAll('.node[data-key]').forEach(n=>{
    const key = 'node.'+n.dataset.key;
    if(dict[key]) n.querySelector('.label-text').textContent = dict[key];
  });
}
document.querySelectorAll('[data-lang-switch] button').forEach(btn=>{
  btn.addEventListener('click', ()=>{
    applyLang(btn.dataset.lang);
    try{ EndoloriStats.bump('langCounts.' + btn.dataset.lang, 1); }catch(e){}
  });
});


applyLang('fr');
